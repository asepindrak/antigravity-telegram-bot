#!/usr/bin/env python3
"""
Antigravity Telegram Bot - Setup & Configuration Wizard
Supports interactive menu and command line flags for automated setup.
Multiplatform: Windows, Linux, macOS.
"""

import os
import sys
import json
import shutil
import platform
import subprocess
import argparse

try:
    import urllib.request
    import urllib.error
except ImportError:
    pass

# Ensure UTF-8 output on Windows consoles
if hasattr(sys.stdout, "reconfigure"):
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass
if hasattr(sys.stderr, "reconfigure"):
    try:
        sys.stderr.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
ENV_FILE = os.path.join(SCRIPT_DIR, ".env")
PROJECTS_FILE = os.path.join(SCRIPT_DIR, "projects.json")
PERSONA_FILE = os.path.join(SCRIPT_DIR, "persona.md")
PERSONAS_DIR = os.path.join(SCRIPT_DIR, "personas")

# ANSI Color codes
GREEN = "\033[92m"
YELLOW = "\033[93m"
CYAN = "\033[96m"
RED = "\033[91m"
BOLD = "\033[1m"
DIM = "\033[2m"
RESET = "\033[0m"

def supports_color():
    if platform.system() == "Windows":
        return os.environ.get("TERM") or os.environ.get("WT_SESSION") or sys.stdout.isatty()
    return sys.stdout.isatty()

COLOR_ENABLED = supports_color()

def c(color, text):
    return f"{color}{text}{RESET}" if COLOR_ENABLED else str(text)

def read_env():
    """Reads .env into a dictionary."""
    env_vars = {}
    if os.path.exists(ENV_FILE):
        try:
            with open(ENV_FILE, "r", encoding="utf-8") as f:
                for line in f:
                    line = line.strip()
                    if line and not line.startswith("#") and "=" in line:
                        k, v = line.split("=", 1)
                        env_vars[k.strip()] = v.strip()
        except Exception as e:
            print(c(RED, f"Error reading .env: {e}"))
    return env_vars

def write_env(env_vars):
    """Writes dictionary back into .env."""
    lines = [
        "# Antigravity Telegram Bot Configuration",
        "# Generated by setup wizard",
        ""
    ]
    for k, v in env_vars.items():
        lines.append(f"{k}={v}")
    try:
        with open(ENV_FILE, "w", encoding="utf-8") as f:
            f.write("\n".join(lines) + "\n")
        return True
    except Exception as e:
        print(c(RED, f"Error saving .env: {e}"))
        return False

def get_masked_token(token):
    if not token:
        return c(RED, "[NOT CONFIGURED ⚠️]")
    if len(token) > 12:
        return f"{token[:5]}...{token[-4:]} {c(GREEN, '✓')}"
    return c(GREEN, "[CONFIGURED ✓]")

def test_telegram_token(token):
    """Queries Telegram getMe endpoint to verify token validity."""
    if not token:
        return False, "Token is empty."
    url = f"https://api.telegram.org/bot{token}/getMe"
    try:
        req = urllib.request.Request(url, headers={"User-Agent": "AntigravityBotSetup/1.0"})
        with urllib.request.urlopen(req, timeout=8) as resp:
            data = json.loads(resp.read().decode("utf-8"))
            if data.get("ok"):
                user = data.get("result", {})
                return True, f"@{user.get('username')} ({user.get('first_name', 'Bot')})"
            return False, data.get("description", "Unknown error")
    except urllib.error.HTTPError as e:
        return False, f"HTTP Error {e.code}: Invalid Token"
    except Exception as e:
        return False, f"Network error: {e}"

def get_active_persona():
    if os.path.exists(PERSONA_FILE):
        try:
            with open(PERSONA_FILE, "r", encoding="utf-8") as f:
                first_line = f.readline().strip()
                return first_line if first_line else "Custom Persona"
        except Exception:
            pass
    return "Not Set (Default)"

def check_agy_installed():
    return shutil.which("agy") is not None

def check_autostart_status():
    system = platform.system()
    if system == "Windows":
        try:
            startup_folder = os.path.join(os.environ.get("APPDATA", ""), "Microsoft", "Windows", "Start Menu", "Programs", "Startup")
            shortcut = os.path.join(startup_folder, "Start_Antigravity_Telegram_Bot.lnk")
            legacy = os.path.join(startup_folder, "Start_AGY_Bridge_and_Telegram_Bot.lnk")
            if os.path.exists(shortcut) or os.path.exists(legacy):
                return True, "Enabled (Windows Startup Folder)"
            return False, "Disabled"
        except Exception:
            return False, "Unknown"
    elif system == "Linux":
        unit = os.path.expanduser("~/.config/systemd/user/antigravity-telegram-bot.service")
        if os.path.exists(unit):
            return True, "Enabled (Systemd user service)"
        return False, "Disabled"
    elif system == "Darwin":
        plist = os.path.expanduser("~/Library/LaunchAgents/com.antigravity.telegrambot.plist")
        if os.path.exists(plist):
            return True, "Enabled (macOS LaunchAgent)"
        return False, "Disabled"
    return False, "Not supported"

def enable_autostart():
    system = platform.system()
    if system == "Windows":
        ps_script = os.path.join(SCRIPT_DIR, "enable_autostart.ps1")
        if os.path.exists(ps_script):
            subprocess.run(["powershell.exe", "-NoProfile", "-ExecutionPolicy", "Bypass", "-File", ps_script], check=False)
            return True
    elif system == "Linux":
        sh_script = os.path.join(SCRIPT_DIR, "enable_autostart.sh")
        if os.path.exists(sh_script):
            subprocess.run(["bash", sh_script], check=False)
            return True
    elif system == "Darwin":
        sh_script = os.path.join(SCRIPT_DIR, "enable_autostart.sh")
        if os.path.exists(sh_script):
            subprocess.run(["bash", sh_script], check=False)
            return True
    print(c(YELLOW, f"Autostart configuration not automated for {system}."))
    return False

def disable_autostart():
    system = platform.system()
    if system == "Windows":
        ps_script = os.path.join(SCRIPT_DIR, "disable_autostart.ps1")
        if os.path.exists(ps_script):
            subprocess.run(["powershell.exe", "-NoProfile", "-ExecutionPolicy", "Bypass", "-File", ps_script], check=False)
            return True
    elif system in ["Linux", "Darwin"]:
        sh_script = os.path.join(SCRIPT_DIR, "disable_autostart.sh")
        if os.path.exists(sh_script):
            subprocess.run(["bash", sh_script], check=False)
            return True
    return False

def set_persona(persona_choice):
    """Sets persona by preset name or file path."""
    source_file = None
    if persona_choice in ["1", "runa"]:
        source_file = os.path.join(PERSONAS_DIR, "runa.md")
    elif persona_choice in ["2", "engineer"]:
        source_file = os.path.join(PERSONAS_DIR, "engineer.md")
    elif persona_choice in ["3", "jarvis"]:
        source_file = os.path.join(PERSONAS_DIR, "jarvis.md")
    elif os.path.isfile(persona_choice):
        source_file = persona_choice
    
    if source_file and os.path.exists(source_file):
        try:
            shutil.copyfile(source_file, PERSONA_FILE)
            print(c(GREEN, f"✓ Persona successfully updated from: {os.path.basename(source_file)}"))
            return True
        except Exception as e:
            print(c(RED, f"Failed to copy persona file: {e}"))
            return False
    else:
        print(c(RED, f"Persona preset or file '{persona_choice}' not found."))
        return False

def manage_projects():
    """Interactive workspace/project manager."""
    projects = {}
    if os.path.exists(PROJECTS_FILE):
        try:
            with open(PROJECTS_FILE, "r", encoding="utf-8") as f:
                projects = json.load(f)
        except Exception:
            projects = {}
    
    print("\n" + c(CYAN, "--- Manage Registered Workspace Projects ---"))
    if not projects:
        print(c(YELLOW, "No projects registered yet."))
    else:
        for idx, (name, path) in enumerate(projects.items(), 1):
            print(f" {idx}. {c(BOLD, name)} -> {path}")
    
    print("\nOptions: [A]dd Project | [R]emove Project | [B]ack")
    sub_choice = input("Select option (A/R/B): ").strip().lower()
    
    if sub_choice == "a":
        p_name = input("Enter project identifier name (e.g., my-app): ").strip()
        p_path = input("Enter directory path (leave blank for ~/<name>): ").strip()
        if not p_name:
            print(c(RED, "Project name cannot be empty."))
            return
        if not p_path:
            p_path = os.path.join(os.path.expanduser("~"), p_name)
        projects[p_name] = os.path.abspath(p_path)
        with open(PROJECTS_FILE, "w", encoding="utf-8") as f:
            json.dump(projects, f, indent=2)
        print(c(GREEN, f"✓ Added project '{p_name}' -> {projects[p_name]}"))
    elif sub_choice == "r":
        p_name = input("Enter project name to remove: ").strip()
        if p_name in projects:
            del projects[p_name]
            with open(PROJECTS_FILE, "w", encoding="utf-8") as f:
                json.dump(projects, f, indent=2)
            print(c(GREEN, f"✓ Removed project '{p_name}'."))
        else:
            print(c(RED, f"Project '{p_name}' not found."))

def start_services():
    system = platform.system()
    if system == "Windows":
        bat = os.path.join(SCRIPT_DIR, "start_services.bat")
        if os.path.exists(bat):
            subprocess.Popen([bat], shell=True, creationflags=subprocess.CREATE_NEW_CONSOLE if hasattr(subprocess, "CREATE_NEW_CONSOLE") else 0)
            print(c(GREEN, "✓ Services launched."))
    else:
        sh = os.path.join(SCRIPT_DIR, "start_services.sh")
        if os.path.exists(sh):
            subprocess.run(["bash", sh], check=False)

def stop_services():
    system = platform.system()
    if system == "Windows":
        bat = os.path.join(SCRIPT_DIR, "stop_services.bat")
        if os.path.exists(bat):
            subprocess.run([bat], shell=True, check=False)
    else:
        sh = os.path.join(SCRIPT_DIR, "stop_services.sh")
        if os.path.exists(sh):
            subprocess.run(["bash", sh], check=False)

def show_interactive_menu():
    while True:
        env_vars = read_env()
        token = env_vars.get("TELEGRAM_BOT_TOKEN", "")
        user_ids = env_vars.get("TELEGRAM_ALLOWED_USER_ID", "")
        persona_name = get_active_persona()
        autostart_ok, autostart_text = check_autostart_status()
        agy_installed = check_agy_installed()
        music_enabled = env_vars.get("MUSIC_FEATURE_ENABLED", "true").lower() in ("true", "1", "yes")
        music_port = env_vars.get("MUSIC_PLAYER_PORT", "8002")

